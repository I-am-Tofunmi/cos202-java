public class ArithmeticOp {
    public static void main(String[] args) {

        // declare variables
        int a = 12, b = 5;

        // addition operator
        System.out.println("a + b = " + (a + b)); // prints 17

        // subtraction operator
        System.out.println("a - b = " + (a - b)); // prints 7

        // multiplication operator
        System.out.println("a * b = " + (a * b)); // prints 60

        // division operator
        System.out.println("a / b = " + (a / b)); // prints 2

        // modulo operator
        System.out.println("a % b = " + (a % b)); // prints 2
    }
}